"""Guardrails: ассистент говорит только о путешествиях по Приморскому краю.

Дешёвый пред-фильтр без LLM (экономит токены на очевидных случаях) + проверка выхода.
Неочевидные случаи решает сама модель через тул decline_request.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

INJECTION = re.compile(
    r"забудь\s+(все\s+|свои\s+|предыдущ\w*\s+)?(правил|инструкц|указан)|игнорируй\s+(все\s+|свои\s+)?(правил|инструкц)"
    r"|ignore\s+(all\s+|previous\s+|the\s+)*(instructions|rules)|system\s*prompt|системн\w+\s+промпт"
    r"|ты\s+(теперь|больше\s+не)\b|режим\s+разработчика|developer\s+mode|\bdan\b|jailbreak|притворись|покажи\s+(свой\s+)?промпт",
    re.I,
)

PRIMORYE = re.compile(
    r"примор|владивосток|находк|уссурийск|артем|артём|партизанск|русск\w+\s+остров|остров\w*\s+русск|о\.\s*русск"
    r"|хасан|андреевк|витяз|гамов|славянк|шамор|лазурн|ханк|лазо|дальнегорск|ольг[аеиу]\b|терне|рощино|ливади"
    r"|шкотов|большой камень|арсеньев|спасск|кавалерово|лесозаводск|дальнереченск|сихотэ|удэге|земл\w+ леопард"
    r"|кедров\w+ пад|остров\w* попов|остров\w* петров|триозерь|триозёрь|пидан|сестр[аыу]\b|токаревск|барабаш"
    r"|золот\w+ рог|амурск\w+ залив|уссурийск\w+ залив|залив\w* восток|залив\w* америк|приморск\w+ кра",
    re.I,
)

OTHER_REGIONS = re.compile(
    r"\b(сочи\b|москв|петербург|питер|спб|урал|кунгур|перм[ьи]|екатеринбург|казан[ьи]|крым|ялт|байкал|иркутск|алта[йя]"
    r"|камчатк|сахалин|хабаровск|карели|калининград|новосибирск|кавказ|дагестан|турци|анталь|египет|таиланд|пхукет"
    r"|япони|токио|китай|китая|пекин|харбин|корея|корею|сеул|вьетнам|европ|париж|мурманск|магадан|якути|владикавказ"
    r"|абхаз|грузи|армени|дубай|бали\b|адлер|анап|геленджик|минск|беларус|казахстан|астан)",
    re.I,
)

TRAVEL = re.compile(
    r"поезд|поездк|путешеств|маршрут|съезд|поех|ехать|отдохн|отдых|выходн|ночев|поход|пляж|куда|погулят|посмотрет"
    r"|достопримечат|план|тур|отел|гостиниц|переноч|экскурс|прогул|велосипед|машин|автобус|пешком|море|бухт|сопк"
    r"|заповедн|музе|остров|день|дня|дней",
    re.I,
)

OFF_TOPIC = re.compile(
    r"алгебр|уравнен|интеграл|производн|реши\s+(мне\s+)?(задач|пример)|домашк|напиши\s+(код|программ|функци|сочинен|эссе|стих)"
    r"|python|javascript|sql|анекдот|шутк|рецепт|курс\s+(валют|доллар)|биткоин|крипт|гороскоп|политик|выбор[ыа]",
    re.I,
)


@dataclass
class GuardVerdict:
    allowed: bool
    category: str = "ok"  # ok | off_topic | other_region | injection | too_long | empty
    message: str = ""


REFUSALS = {
    "off_topic": "Сие не о странствиях. Аз, тигрёнок-летописец Амба, веду лишь путевые грамоты по Приморскому краю — "
                 "спроси меня, куда поехать, и я начертаю маршрут.",
    "other_region": "Земли сии лежат за пределами Приморского края, и путей туда я не ведаю. "
                    "Могу составить грамоту по Приморью: Владивосток, Находка, Хасан, Ханка, Сихотэ-Алинь…",
    "injection": "Правил своих не забываю и роли не меняю: я — летописец странствий по Приморью. "
                 "Расскажи, куда хочешь отправиться, — и начнём.",
    "too_long": "Слишком длинна челобитная. Опиши поездку короче — в пару предложений.",
    "empty": "Грамота пуста. Напиши, куда и как хочешь поехать.",
}


def precheck(query: str, max_chars: int = 600) -> GuardVerdict:
    q = (query or "").strip()
    if not q:
        return GuardVerdict(False, "empty", REFUSALS["empty"])
    if len(q) > max_chars:
        return GuardVerdict(False, "too_long", REFUSALS["too_long"])
    if INJECTION.search(q):
        return GuardVerdict(False, "injection", REFUSALS["injection"])
    has_primorye = bool(PRIMORYE.search(q))
    if OTHER_REGIONS.search(q) and not has_primorye:
        return GuardVerdict(False, "other_region", REFUSALS["other_region"])
    if OFF_TOPIC.search(q) and not TRAVEL.search(q):
        return GuardVerdict(False, "off_topic", REFUSALS["off_topic"])
    return GuardVerdict(True)
